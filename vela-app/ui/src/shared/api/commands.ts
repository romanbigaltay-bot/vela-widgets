/**
 * Реестр команд IPC.
 *
 * # Почему команд мало
 *
 * Объявление команды — обещание, что обработчик существует и его сигнатура
 * не изменится. Плодить тридцать объявлений `layout.*`, `scene.*`, `capture.*`
 * заранее значило бы угадывать сигнатуры: к моменту реализации половина
 * изменится, а вторая окажется ненужной. Тот же принцип, что и с
 * репозиториями (D-13 в STATUS).
 *
 * # Как добавить команду
 *
 * 1. Объявить типы запроса и ответа в Rust. Команды живут в
 *    `crates/vela-ipc/src/commands/`, когда их станет больше одной.
 * 2. Выполнить `pnpm ipc:gen` — типы появятся в этом каталоге.
 * 3. Добавить строку в `InvokeMap` ниже.
 * 4. Реализовать обработчик в `apps/desktop` и зарегистрировать его в Tauri.
 *
 * После шага 3 `call('window.surfaces_status', ...)` типизирован: имя команды
 * проверяется компилятором, ответ приходит с правильным типом, а опечатка
 * в имени — ошибка сборки, а не пустой экран у пользователя.
 */

import type { SurfaceStatus } from './SurfaceStatus';

/**
 * Форма реестра: имя команды → типы запроса и ответа.
 *
 * `res` — это то, что лежит в `Envelope.data`, без самой обёртки: клиент
 * разворачивает конверт и отдаёт вызывающему чистые данные.
 *
 * Интерфейс намеренно пуст: конкретные команды объявляются в `InvokeMap`.
 * Индексной сигнатуры `[command: string]` здесь нет — с ней `call('опечатка')`
 * компилировался бы, и обещание «имя проверяет компилятор» было бы ложным.
 */
export interface CommandMap {}

/**
 * Команды, известные этой сборке UI.
 *
 * `InvokeMap` расширяет `CommandMap`, чтобы `call()` компилировался, а
 * добавление команды было однострочным. `no-empty-object-type` отключён
 * здесь осознанно: интерфейс — это точка расширения через слияние
 * объявлений, а `type` для этого не годится.
 */
export interface InvokeMap extends CommandMap {
  /**
   * Снимок всех поверхностей: тип, монитор, видимость и логический размер.
   *
   * Запроса нет: команда возвращает состояние целиком. Отдельный
   * `surface.get` появится, когда поверхностей станет много и понадобится
   * точечное обновление.
   */
  'window.surfaces_status': { req: undefined; res: SurfaceStatus[] };
}
