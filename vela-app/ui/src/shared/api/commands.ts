/**
 * Реестр команд IPC.
 *
 * # Почему файл пуст в P1
 *
 * Команд пока не существует: ядро Tauri подключается в P2 (`ST-0201-01`),
 * а обработчики — вместе с теми задачами, которые ими пользуются. Плодить
 * тридцать объявлений `layout.*`, `scene.*`, `capture.*` заранее значило бы
 * угадывать сигнатуры: к моменту реализации половина изменится, а вторая
 * окажется ненужной. Тот же принцип, что и с репозиториями (D-13 в STATUS).
 *
 * # Как добавить команду
 *
 * 1. Объявить типы запроса и ответа в Rust (`crates/vela-ipc/src/commands/`).
 * 2. Выполнить `pnpm ipc:gen` — типы появятся в этом каталоге.
 * 3. Добавить строку в `InvokeMap` ниже.
 * 4. Реализовать обработчик в `apps/desktop` и зарегистрировать его в Tauri.
 *
 * После шага 3 `call('layout.get', ...)` типизирован: имя команды проверяется
 * компилятором, ответ приходит с правильным типом, а опечатка в имени —
 * ошибка сборки, а не пустой экран у пользователя.
 */

/**
 * Форма реестра: имя команды → типы запроса и ответа.
 *
 * `res` — это то, что лежит в `Envelope.data`, без самой обёртки: клиент
 * разворачивает конверт и отдаёт вызывающему чистые данные.
 */
export interface CommandMap {
  readonly [command: string]: {
    readonly req: unknown;
    readonly res: unknown;
  };
}

/**
 * Команды, известные этой сборке UI.
 *
 * Пока пусто: команд нет до P2. Тип `InvokeMap` объявлен как расширение
 * `CommandMap`, чтобы `call()` компилировался, а добавление команды было
 * однострочным. `no-empty-object-type` отключён здесь осознанно: интерфейс
 * без собственных членов — это точка расширения через слияние объявлений,
 * а `type` для этого не годится.
 */
export interface InvokeMap extends CommandMap {}
