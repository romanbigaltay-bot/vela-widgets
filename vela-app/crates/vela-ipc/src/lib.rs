//! Контракты между Rust-ядром и UI.
//!
//! # Правила крейта
//!
//! * Никаких `tauri`, `windows`, `winit` — контракты обязаны собираться в
//!   обычном `cargo test` без графической среды (проверяется `tests/graph_rules.rs`).
//! * Никаких голых `String` в публичных типах: все идентификаторы — newtype,
//!   чтобы «перепутать элемент с монитором» было ошибкой компиляции.
//! * Любое изменение публичного типа обязано перегенерировать TS (`pnpm ipc:gen`)
//!   и не оставить диффа в CI.
//!
//! # Почему «конверт»
//!
//! Tauri возвращает `Result<T, E>` на транспортном уровне, но фронтенду нужны
//! стабильные коды ошибок, а не строки. Поэтому все команды возвращают
//! [`Envelope`]: он несёт либо данные, либо [`VelaError`] с [`ErrorCode`].
//! UI обрабатывает `code`, а `message` показывает только в диагностике.

// Тесты могут паниковать: `unwrap()` там — это утверждение об ожидаемом
// результате, а не обработка ошибки (см. clippy.toml, unwrap_used).
#![cfg_attr(test, allow(clippy::unwrap_used, clippy::expect_used))]

pub mod envelope;
pub mod errors;
pub mod ids;

pub use envelope::{Envelope, UnitEnvelope};
pub use errors::{ErrorCode, VelaError};
pub use ids::{ElementId, MonitorId, ProfileId, WidgetId};

/// Идентификатор сборки крейта контрактов.
pub fn health() -> &'static str {
    "vela-ipc"
}

/// Версия контракта IPC.
///
/// Растёт при несовместимом изменении: например, при переименовании команды
/// или смене семантики поля. UI может сравнить версию до первого вызова.
///
/// В отличие от версии схемы БД (`vela_core::SCHEMA_VERSION`), эта версия
/// не про данные пользователя, а про совместимость «бинарь ↔ собранный UI».
pub const IPC_VERSION: u32 = 1;

// Инвариант проверяется компилятором, а не тестом: нулевая версия контракта
// означала бы «контракта нет», и это должно ломать сборку, а не CI.
const _: () = assert!(IPC_VERSION >= 1);

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn health_is_stable() {
        assert_eq!(health(), "vela-ipc");
    }
}
